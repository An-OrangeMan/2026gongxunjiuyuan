  /*Configure GPIO pins : PCPin PCPin */
  GPIO_InitStruct.Pin = IMU_SCL_Pin|IMU_SDA_Pin;
  GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
  GPIO_InitStruct.Pull = GPIO_PULLUP;
